-- Set the sequences as buffer-local mappings in buffer `buf` (0 for the
-- current one).
function M.map(buf)
    for _, s in ipairs(M.sequences) do
        vim.keymap.set({"i", "c"}, "<LocalLeader>" .. s[1], s[2], {buffer = buf})
    end
end

return M
